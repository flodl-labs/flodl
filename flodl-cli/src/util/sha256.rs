//! SHA-256, the FIPS 180-4 construction, for content digests.
//!
//! flodl-cli takes no dependencies, and the run manifest needs a stable
//! content hash that a worker can recompute and an operator can check by
//! hand (`sha256sum -c`). Streaming so a file is hashed without being held
//! in memory; correctness is pinned by the NIST vectors in the tests.

